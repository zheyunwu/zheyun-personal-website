import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { geoOrthographic, geoPath, geoGraticule } from 'd3-geo';
import { feature } from 'topojson-client';

const root = new URL('../', import.meta.url);
const atlas = JSON.parse(await readFile(new URL('scripts/map-data/land-50m.json', root), 'utf8'));
const locations = JSON.parse(await readFile(new URL('content/life-locations.json', root), 'utf8'));
const width = 760;
const height = 620;
// Keep the hemisphere and location overlay on one geographical projection.
const projection = geoOrthographic()
  .rotate([-65, -32])
  .translate([380, 310])
  .scale(242)
  .precision(0.2);
const path = geoPath(projection).digits(1);
const land = feature(atlas, atlas.objects.land);
const graticule = geoGraticule().step([20, 20]);

// Remove sub-pixel vertices after projection, without coarsening the source
// geography. A tolerance of 0.08 SVG units is below one tenth of a CSS pixel
// even when the artwork is displayed at its full 760px width.
function simplifyLine(points, tolerance = 0.08) {
  if (points.length <= 2) return points;
  const first = points[0];
  const last = points.at(-1);
  const dx = last[0] - first[0];
  const dy = last[1] - first[1];
  const lengthSquared = dx * dx + dy * dy;
  let greatestDistance = tolerance * tolerance;
  let split = -1;
  for (let index = 1; index < points.length - 1; index++) {
    const [x, y] = points[index];
    const fraction = lengthSquared
      ? Math.max(0, Math.min(1, ((x - first[0]) * dx + (y - first[1]) * dy) / lengthSquared))
      : 0;
    const distance = (x - first[0] - fraction * dx) ** 2 + (y - first[1] - fraction * dy) ** 2;
    if (distance > greatestDistance) {
      greatestDistance = distance;
      split = index;
    }
  }
  return split < 0 ? [first, last] : [
    ...simplifyLine(points.slice(0, split + 1), tolerance).slice(0, -1),
    ...simplifyLine(points.slice(split), tolerance),
  ];
}

const coastlineProjection = {
  stream(sink) {
    let line;
    return projection.stream({
      polygonStart: () => sink.polygonStart(),
      polygonEnd: () => sink.polygonEnd(),
      lineStart: () => { line = []; },
      lineEnd: () => {
        sink.lineStart();
        for (const point of simplifyLine(line)) sink.point(...point);
        sink.lineEnd();
        line = undefined;
      },
      point: (x, y) => line ? line.push([x, y]) : sink.point(x, y),
    });
  },
};
const coastPath = geoPath(coastlineProjection).digits(1)(land);
const svg = `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${width} ${height}" fill="none">
<!-- Natural Earth public-domain geography at 1:50m, world-atlas 2.0.2. Generated by scripts/generate-life-map.mjs. -->
<defs>
  <linearGradient id="ocean" x1="195" y1="110" x2="548" y2="535" gradientUnits="userSpaceOnUse">
    <stop stop-color="#f0f4f6"/>
    <stop offset=".55" stop-color="#e9eff2"/>
    <stop offset="1" stop-color="#dce6ed"/>
  </linearGradient>
  <radialGradient id="surface-light" cx=".34" cy=".25" r=".8">
    <stop stop-color="#fff" stop-opacity=".22"/>
    <stop offset=".55" stop-color="#fff" stop-opacity="0"/>
    <stop offset=".8" stop-color="#71899c" stop-opacity=".025"/>
    <stop offset="1" stop-color="#71899c" stop-opacity=".13"/>
  </radialGradient>
  <clipPath id="hemisphere"><circle cx="380" cy="310" r="242"/></clipPath>
</defs>
<rect width="760" height="620" fill="#faf9f6"/>
<g clip-path="url(#hemisphere)">
  <circle cx="380" cy="310" r="242" fill="url(#ocean)"/>
  <path d="${path(graticule())}" stroke="#a9bbc7" stroke-opacity=".4" stroke-width=".6"/>
  <path d="${coastPath}" fill="#fafaf6" stroke="#98acb5" stroke-width=".52" stroke-linejoin="round"/>
  <circle cx="380" cy="310" r="242" fill="url(#surface-light)"/>
</g>
<circle cx="380" cy="310" r="241.7" stroke="#a3b5c0" stroke-opacity=".55" stroke-width=".6"/>
</svg>\n`;
await writeFile(new URL('public/images/life-map-base.svg', root), svg);
const points = locations.map(({id,coordinates})=>({id,point:projection(coordinates).map(value=>Number(value.toFixed(3)))}));
await writeFile(new URL('content/life-map-points.json', root), JSON.stringify({width,height,points},null,2)+'\n');
console.log(`Generated ${fileURLToPath(new URL('public/images/life-map-base.svg', root))} (${Buffer.byteLength(svg)} bytes)`);
