import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { geoNaturalEarth1, geoPath, geoGraticule } from 'd3-geo';
import { feature } from 'topojson-client';

const root = new URL('../', import.meta.url);
const atlas = JSON.parse(await readFile(new URL('scripts/map-data/land-110m.json', root), 'utf8'));
const locations = JSON.parse(await readFile(new URL('content/life-locations.json', root), 'utf8'));
const width = 720;
const height = 540;
const projection = geoNaturalEarth1().rotate([-12, 0]).fitExtent([[18, 125], [702, 485]], { type: 'Sphere' });
const path = geoPath(projection).digits(2);
const land = feature(atlas, atlas.objects.land);
const graticule = geoGraticule().step([30, 30]);
const svg = `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${width} ${height}" fill="none">
<!-- Natural Earth public-domain geography, world-atlas 2.0.2. Generated by scripts/generate-life-map.mjs. -->
<path d="${path(graticule())}" stroke="#dfe5ec" stroke-width=".65"/>
<path d="${path(land)}" fill="#d3dde6" stroke="#becbd7" stroke-width=".55" stroke-linejoin="round"/>
</svg>\n`;
await writeFile(new URL('public/images/life-map-base.svg', root), svg);
const points = locations.map(({id,coordinates})=>({id,point:projection(coordinates).map(value=>Number(value.toFixed(3)))}));
await writeFile(new URL('content/life-map-points.json', root), JSON.stringify({width,height,points},null,2)+'\n');
console.log(`Generated ${fileURLToPath(new URL('public/images/life-map-base.svg', root))} (${Buffer.byteLength(svg)} bytes)`);
